#!/usr/bin/env python3
"""Convert Lucide SVG icons (24x24, stroke based) into one JS dictionary of path strings."""
import sys, glob, os, re, json
import xml.etree.ElementTree as ET

NS = "{http://www.w3.org/2000/svg}"
def f(v, d=0.0): return float(v) if v is not None else d

def elem_to_path(e):
    t = e.tag.replace(NS, "")
    a = e.attrib
    if t == "path": return a["d"]
    if t == "line":
        return f"M{a['x1']} {a['y1']}L{a['x2']} {a['y2']}"
    if t in ("polyline", "polygon"):
        pts = re.split(r"[ ,]+", a["points"].strip())
        pairs = list(zip(pts[0::2], pts[1::2]))
        d = "M" + "L".join(f"{x} {y}" for x, y in pairs)
        return d + ("Z" if t == "polygon" else "")
    if t == "circle":
        cx, cy, r = f(a["cx"]), f(a["cy"]), f(a["r"])
        return f"M{cx-r} {cy}A{r} {r} 0 1 0 {cx+r} {cy}A{r} {r} 0 1 0 {cx-r} {cy}Z"
    if t == "ellipse":
        cx, cy, rx, ry = f(a["cx"]), f(a["cy"]), f(a["rx"]), f(a["ry"])
        return f"M{cx-rx} {cy}A{rx} {ry} 0 1 0 {cx+rx} {cy}A{rx} {ry} 0 1 0 {cx-rx} {cy}Z"
    if t == "rect":
        x, y, w, h = f(a.get("x")), f(a.get("y")), f(a["width"]), f(a["height"])
        rx = f(a.get("rx"), f(a.get("ry")))
        if rx <= 0: return f"M{x} {y}H{x+w}V{y+h}H{x}Z"
        return (f"M{x+rx} {y}H{x+w-rx}A{rx} {rx} 0 0 1 {x+w} {y+rx}V{y+h-rx}"
                f"A{rx} {rx} 0 0 1 {x+w-rx} {y+h}H{x+rx}A{rx} {rx} 0 0 1 {x} {y+h-rx}"
                f"V{y+rx}A{rx} {rx} 0 0 1 {x+rx} {y}Z")
    return None

NUM = r"[-+]?(?:\d*\.\d+|\d+\.?)(?:[eE][-+]?\d+)?"

def abs_start(d):
    """Make a path that starts with a relative 'm' start with an absolute 'M'.
    The coordinate pair becomes absolute (it is, at the origin of its own element);
    any implicit follow-up pairs stay relative via an explicit 'l'."""
    if not d.startswith("m"):
        return d
    m = re.match(r"m\s*(" + NUM + r")[\s,]*(" + NUM + r")(.*)$", d, re.S)
    x, y, rest = m.group(1), m.group(2), m.group(3)
    if rest and (rest[0] in "-+." or rest[0].isdigit() or rest[0].isspace()):
        rest = "l" + rest.lstrip()
    return f"M{x} {y}{rest}"

def main(src, out):
    icons = {}
    for p in sorted(glob.glob(os.path.join(src, "*.svg"))):
        name = os.path.basename(p)[:-4]
        root = ET.parse(p).getroot()
        parts = [elem_to_path(e) for e in root.iter() if e is not root]
        parts = [x for x in parts if x]
        # Each SVG element starts at the origin: a leading relative "m" is absolute there.
        parts = [abs_start(x) for x in parts]
        icons[name] = "".join(parts)
    with open(out, "w") as fh:
        fh.write(".pragma library\n// Generated by tools/svg2js.py from Lucide icons (ISC license, see assets/LICENSE-lucide.txt)\n")
        fh.write("var paths = " + json.dumps(icons, indent=1) + ";\n")
        fh.write("function path(name) { return paths[name] || \"\"; }\n")
    print(len(icons), "icons ->", out)

if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
